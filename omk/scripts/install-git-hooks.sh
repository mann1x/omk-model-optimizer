#!/usr/bin/env bash
# install-git-hooks.sh — install the gitleaks pre-commit secret gate (omk/gitleaks.toml).
#
#     bash omk/scripts/install-git-hooks.sh
#
# .git/hooks is not tracked, so a fresh clone has no gate until this runs. The hook scans the STAGED diff and
# blocks the commit on any finding. If gitleaks is missing it refuses the commit (it does not silently pass).
# The same config runs in CI on every push (.github/workflows/omk-gitleaks.yml), over every commit omk adds.
set -euo pipefail
ROOT="$(git rev-parse --show-toplevel)"
HOOK="$ROOT/.git/hooks/pre-commit"
cat > "$HOOK" <<'EOF'
#!/usr/bin/env bash
# AUTO-GENERATED by omk/scripts/install-git-hooks.sh — gitleaks staged-secret gate. Edit the generator.
ROOT="$(git rev-parse --show-toplevel)"
G=$(command -v gitleaks || echo /usr/local/bin/gitleaks)
if [ ! -x "$G" ]; then
  echo "gitleaks not found: commit REFUSED. Install it (https://github.com/gitleaks/gitleaks/releases), then retry." >&2
  exit 1
fi
exec "$G" git --staged --no-banner --redact --config "$ROOT/omk/gitleaks.toml"
EOF
chmod +x "$HOOK"
echo "installed $HOOK ($(command -v gitleaks >/dev/null && gitleaks version || echo 'gitleaks NOT on PATH'))"
